export function characterGuide(char: string, category: CharCategory) {
  if (category === "special-symbol")
    return "견본을 보고 기호의 모양과 높이를 맞춰 써주세요.";
  if (symbols[char]) return symbols[char];
  if (category === "latin-upper")
    return `영문 대문자 ${char}예요. 위쪽 높이선과 기준선을 참고해 써주세요.`;
  if (category === "latin-lower")
    return `영문 소문자 ${char}예요. ${/[gjpqy]/.test(char) ? "꼬리가 기준선 아래로 내려가는 글자예요." : "소문자 높이선과 기준선을 참고해 써주세요."}`;
  if (category === "digit")
    return `숫자 ${char}예요. 다른 숫자와 높이를 맞춰 써주세요.`;
  if (category === "hangul-jamo")
    return `한글 낱자 ${char}예요. 자음이나 모음을 단독으로 쓸 때의 모양을 적어주세요.`;
  return "한글 조합에 필요한 글자예요. 낯선 글자도 견본 모양을 보고 한 획씩 써주세요.";
}
