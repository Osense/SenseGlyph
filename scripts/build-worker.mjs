import { build } from "esbuild";
import { createHash } from "node:crypto";
import { readdir, unlink, writeFile } from "node:fs/promises";

const result = await build({
  entryPoints: ["workers/font.worker.ts"],
  outfile: "public/font-worker.js",
  bundle: true,
  platform: "browser",
  format: "iife",
  target: "es2022",
  minify: true,
  legalComments: "eof",
  write: false,
});
const bytes = result.outputFiles[0].contents;
const name =
  "font-worker." +
  createHash("sha256").update(bytes).digest("hex").slice(0, 12) +
  ".js";
for (const file of await readdir("public"))
  if (/^font-worker(?:\.[a-f0-9]{12})?\.js$/.test(file))
    await unlink("public/" + file);
await writeFile("public/" + name, bytes);
await writeFile(
  "lib/font/worker-url.ts",
  "/* Generated by scripts/build-worker.mjs */\n" +
    'import { BASE_PATH } from "../base-path";\n' +
    "export const FONT_WORKER_URL = BASE_PATH + " +
    JSON.stringify("/" + name) +
    ";\n",
);
console.log("Local font worker bundled");
