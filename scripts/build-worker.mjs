import { build } from "esbuild";
import { createHash } from "node:crypto";
import { basename } from "node:path";
import { readdir, unlink, writeFile } from "node:fs/promises";

const result = await build({
  entryPoints: {
    "font-worker": "workers/font.worker.ts",
    "font-export-worker": "workers/font-export.worker.ts",
  },
  outdir: "public",
  bundle: true,
  platform: "browser",
  format: "iife",
  target: "es2022",
  minify: true,
  legalComments: "eof",
  write: false,
});
for (const file of await readdir("public"))
  if (/^font(?:-export)?-worker(?:\.[a-f0-9]{12})?\.js$/.test(file))
    await unlink("public/" + file);

const urls = {};
for (const output of result.outputFiles) {
  const entry = basename(output.path, ".js");
  const hash = createHash("sha256")
    .update(output.contents)
    .digest("hex")
    .slice(0, 12);
  const name = entry + "." + hash + ".js";
  await writeFile("public/" + name, output.contents);
  urls[entry] = "/" + name;
}
await writeFile(
  "lib/font/worker-url.ts",
  "/* Generated by scripts/build-worker.mjs */\n" +
    'import { BASE_PATH } from "../base-path";\n' +
    "export const FONT_WORKER_URL = BASE_PATH + " +
    JSON.stringify(urls["font-worker"]) +
    ";\n" +
    "export const FONT_EXPORT_WORKER_URL = BASE_PATH + " +
    JSON.stringify(urls["font-export-worker"]) +
    ";\n",
);
console.log("Local font workers bundled");
